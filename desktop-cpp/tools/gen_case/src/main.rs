// Writes core/src/text_case.inc: the case mapping of Rust's char::to_lowercase and to_uppercase, and the two
// properties str::to_lowercase reads for the final sigma, taken from the Rust standard library this runs on.
// Run from desktop-cpp: cargo run --manifest-path tools/gen_case/Cargo.toml > core/src/text_case.inc
use std::fmt::Write;

// A run of code points that map by one delta: first, last, the step between them (1 or 2), and the delta.
struct Run {
	first: u32,
	last: u32,
	step: u32,
	delta: i64,
}

// Packs sorted (code point, mapped code point) pairs into runs of one delta and one step.
fn runs(pairs: &[(u32, u32)]) -> Vec<Run> {
	let mut out: Vec<Run> = Vec::new();
	for &(c, m) in pairs {
		let delta = m as i64 - c as i64;
		if let Some(r) = out.last_mut() {
			// A run of one takes the step of its second code point; a longer run keeps its step.
			let gap = c - r.last;
			if r.delta == delta && ((r.first == r.last && (gap == 1 || gap == 2)) || (r.first != r.last && gap == r.step)) {
				r.step = gap;
				r.last = c;
				continue;
			}
		}
		out.push(Run { first: c, last: c, step: 1, delta });
	}
	out
}

// Packs a sorted set of code points into inclusive ranges.
fn ranges(set: &[u32]) -> Vec<(u32, u32)> {
	let mut out: Vec<(u32, u32)> = Vec::new();
	for &c in set {
		match out.last_mut() {
			Some(r) if r.1 + 1 == c => r.1 = c,
			_ => out.push((c, c)),
		}
	}
	out
}

fn utf8_literal(s: &str) -> String {
	s.bytes().map(|b| format!("\\x{b:02X}")).collect()
}

fn main() {
	let chars = || (0..=0x10FFFFu32).filter_map(char::from_u32);
	let mut lower = Vec::new();
	let mut upper = Vec::new();
	let mut lower_multi = Vec::new();
	let mut upper_multi = Vec::new();
	let mut ignorable = Vec::new();
	let mut cased = Vec::new();
	for c in chars() {
		let l: Vec<char> = c.to_lowercase().collect();
		if l.len() == 1 && l[0] != c {
			lower.push((c as u32, l[0] as u32));
		} else if l.len() > 1 {
			lower_multi.push((c as u32, l.iter().collect::<String>()));
		}
		let u: Vec<char> = c.to_uppercase().collect();
		if u.len() == 1 && u[0] != c {
			upper.push((c as u32, u[0] as u32));
		} else if u.len() > 1 {
			upper_multi.push((c as u32, u.iter().collect::<String>()));
		}
		// The final sigma: "xΣ" lowercases to a final sigma when x is cased and not case-ignorable; "AxΣ" does
		// when x is case-ignorable (skipped, so "A" counts) or cased. Rust reads Cased only of a code point that
		// is not Case_Ignorable, so the cased set below holds only those.
		let alone = format!("{c}\u{3A3}").to_lowercase().ends_with('\u{3C2}');
		let after_a = format!("A{c}\u{3A3}").to_lowercase().ends_with('\u{3C2}');
		if after_a && !alone {
			ignorable.push(c as u32);
		}
		if alone {
			cased.push(c as u32);
		}
	}

	let mut out = String::new();
	let version = std::process::Command::new("rustc")
		.arg("--version")
		.output()
		.map(|o| String::from_utf8_lossy(&o.stdout).trim().to_string())
		.unwrap_or_default();
	writeln!(out, "// Generated by tools/gen_case from the standard library of {version}; do not edit.").unwrap();
	writeln!(out, "// Regenerate with: cargo run --manifest-path tools/gen_case/Cargo.toml > core/src/text_case.inc").unwrap();
	for (name, pairs) in [("LOWER_RUNS", &lower), ("UPPER_RUNS", &upper)] {
		let rs = runs(pairs);
		writeln!(out, "constexpr std::array<CaseRun, {}> {name} = {{{{", rs.len()).unwrap();
		for r in rs {
			writeln!(out, "\t{{0x{:X}, 0x{:X}, {}, {}}},", r.first, r.last, r.step, r.delta).unwrap();
		}
		writeln!(out, "}}}};").unwrap();
	}
	for (name, list) in [("LOWER_MULTI", &lower_multi), ("UPPER_MULTI", &upper_multi)] {
		writeln!(out, "constexpr std::array<CaseMulti, {}> {name} = {{{{", list.len()).unwrap();
		for (c, s) in list {
			writeln!(out, "\t{{0x{c:X}, \"{}\"}},", utf8_literal(s)).unwrap();
		}
		writeln!(out, "}}}};").unwrap();
	}
	for (name, set) in [("CASE_IGNORABLE", &ignorable), ("CASED", &cased)] {
		let rs = ranges(set);
		writeln!(out, "constexpr std::array<CpRange, {}> {name} = {{{{", rs.len()).unwrap();
		for (a, b) in rs {
			writeln!(out, "\t{{0x{a:X}, 0x{b:X}}},").unwrap();
		}
		writeln!(out, "}}}};").unwrap();
	}
	print!("{out}");
}
